BEGIN;

ALTER TABLE properties
  ADD COLUMN IF NOT EXISTS currency VARCHAR(3) NOT NULL DEFAULT 'INR',
  ADD COLUMN IF NOT EXISTS gst_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS gst_rate NUMERIC(5,2) NOT NULL DEFAULT 18.00,
  ADD COLUMN IF NOT EXISTS price_includes_gst BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE properties DROP CONSTRAINT IF EXISTS properties_gst_rate_check;
ALTER TABLE properties ADD CONSTRAINT properties_gst_rate_check
  CHECK (gst_rate >= 0 AND gst_rate <= 100);

ALTER TABLE properties DROP CONSTRAINT IF EXISTS properties_currency_check;
ALTER TABLE properties ADD CONSTRAINT properties_currency_check
  CHECK (currency ~ '^[A-Z]{3}$');

ALTER TABLE enquiries
  ADD COLUMN IF NOT EXISTS taxable_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS gst_rate NUMERIC(5,2),
  ADD COLUMN IF NOT EXISTS cgst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS sgst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS igst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS gst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS currency VARCHAR(3),
  ADD COLUMN IF NOT EXISTS price_includes_gst BOOLEAN;

ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS taxable_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS gst_rate NUMERIC(5,2),
  ADD COLUMN IF NOT EXISTS cgst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS sgst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS igst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS gst_amount NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS currency VARCHAR(3),
  ADD COLUMN IF NOT EXISTS price_includes_gst BOOLEAN;

COMMIT;
